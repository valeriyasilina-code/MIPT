"""Задача Pandas: экспрессия гена в двух экспериментальных группах."""
import pandas as pd

df = pd.DataFrame({
    "Образец": ["A1", "A2", "A3", "B1", "B2", "B3"],
    "Группа": ["A", "A", "A", "B", "B", "B"],
    "Экспрессия": [10, 15, None, 20, 25, 18],
})
print("Исходная таблица:")
print(df, "\n")

# 1. Первые три строки
print("1. Первые три строки:")
print(df.head(3), "\n")

# 2. Пропущенные значения
print("2. Где пропуски (True = NaN):")
print(df.isna(), "\n")
print("Число пропусков по столбцам:")
print(df.isna().sum(), "\n")
print("Строки с пропусками:")
print(df[df.isna().any(axis=1)], "\n")

# 3. Удалить строки без значения экспрессии
clean = df.dropna(subset=["Экспрессия"]).reset_index(drop=True)
print("3. Очищенная таблица:")
print(clean, "\n")

# 4. Образцы с экспрессией не ниже 18 (>= 18)
high = clean[clean["Экспрессия"] >= 18]
print("4. Экспрессия >= 18:")
print(high, "\n")
print("Список образцов:", high["Образец"].tolist(), "\n")

# 5. Средняя экспрессия по группам
means = clean.groupby("Группа")["Экспрессия"].mean()
print("5. Средняя экспрессия по группам:")
print(means)
